#!/usr/bin/env bash
# Provision (or update) HarmonyHub on AWS and deploy the current commit.
#
#   ./infra/aws-up.sh
#
# Creates with Terraform: SSH key pair, security group, EC2 instance (Ubuntu 24.04, t3.small), Elastic IP.
# Then uploads the committed code plus a production .env built from your local .env files, and starts
# docker compose with Caddy serving https://<elastic-ip>. Safe to rerun: it updates instead of recreating.
#
# Optional settings (environment variables):
#   TF_VAR_region         AWS region (default ap-south-1)
#   TF_VAR_instance_type  EC2 type (default t3.small)
#   HH_ENV_FILES          local env files to read, later ones win (default ".env backend/.env")
set -euo pipefail
source "$(dirname "$0")/lib.sh"

require terraform aws ssh scp curl git tar openssl awk
aws sts get-caller-identity >/dev/null 2>&1 || die "The AWS CLI is not logged in. Run 'aws configure' first."
mkdir -p "$SECRETS_DIR"

# ---------------------------------------------------------------------------
say "1/5 Provisioning AWS resources with Terraform"
MY_IP="$(curl -fsS https://checkip.amazonaws.com | tr -d '[:space:]')"
[ -n "$MY_IP" ] || die "Could not detect your public IP."
tf init -input=false >/dev/null
tf apply -input=false -auto-approve -var "ssh_cidr=${MY_IP}/32"
PUBLIC_IP="$(tf output -raw public_ip)"
chmod 600 "$SSH_KEY"
echo "Server IP: $PUBLIC_IP (SSH allowed from $MY_IP)"

# ---------------------------------------------------------------------------
say "2/5 Building the production .env"
cd "$REPO_DIR"
read -r -a env_files <<< "${HH_ENV_FILES:-.env backend/.env}"
existing=()
for file in "${env_files[@]}"; do
  if [ -f "$file" ]; then existing+=("$file"); fi
done
[ ${#existing[@]} -gt 0 ] || die "No env file found (looked for: ${env_files[*]}). Copy .env.example to .env and fill it in."

# Merge KEY=VALUE lines (later files win). Values that only make sense on a laptop are dropped;
# docker compose and this script set them for the server.
DROP_KEYS="DATABASE_URL REDIS_URL PYTHON_RECOMMENDER_HOST PYTHON_RECOMMENDER_PORT PYTHON_RECOMMENDER_URL PORT POSTGRES_PORT REDIS_PORT CORS_ORIGIN FRONTEND_URL SPOTIFY_REDIRECT_URI PUBLIC_IP POSTGRES_PASSWORD NODE_ENV"
merged="$(awk -v drop="$DROP_KEYS" '
  BEGIN { n = split(drop, d, " "); for (i = 1; i <= n; i++) skip[d[i]] = 1 }
  { sub(/\r$/, "") }
  /^[[:space:]]*#/ || /^[[:space:]]*$/ || !/=/ { next }
  {
    key = $0; sub(/=.*/, "", key); gsub(/[[:space:]]/, "", key)
    value = $0; sub(/^[^=]*=/, "", value)
    if (key in skip) next
    if (!(key in seen)) { order[++count] = key; seen[key] = 1 }
    values[key] = value
  }
  END { for (i = 1; i <= count; i++) if (values[order[i]] != "") print order[i] "=" values[order[i]] }
' "${existing[@]}")"

has_value() { printf '%s\n' "$merged" | grep -q "^$1=."; }
has_value SPOTIFY_CLIENT_ID && has_value SPOTIFY_CLIENT_SECRET \
  || die "SPOTIFY_CLIENT_ID and SPOTIFY_CLIENT_SECRET must be set in ${existing[*]}."
has_value GOOGLE_API_KEY || warn "GOOGLE_API_KEY is empty: AI playlists will fall back to Spotify search."

PROD_ENV="$SECRETS_DIR/prod.env"
(
  umask 077
  {
    echo "# Generated by infra/aws-up.sh from ${existing[*]}. Do not commit."
    printf '%s\n' "$merged"
    # Missing app secrets are generated once and kept in infra/.secrets, so redeploys keep sessions and data.
    has_value TOKEN_ENCRYPTION_KEY \
      || echo "TOKEN_ENCRYPTION_KEY=$(persisted_secret token_encryption_key openssl rand -base64 32)"
    has_value RECOMMENDER_INTERNAL_TOKEN \
      || echo "RECOMMENDER_INTERNAL_TOKEN=$(persisted_secret recommender_token openssl rand -hex 32)"
    echo "POSTGRES_PASSWORD=$(persisted_secret postgres_password openssl rand -hex 24)"
    echo "PUBLIC_IP=$PUBLIC_IP"
    echo "FRONTEND_URL=https://$PUBLIC_IP"
    echo "SPOTIFY_REDIRECT_URI=https://$PUBLIC_IP/api/auth/spotify/callback"
  } > "$PROD_ENV"
)
echo "Wrote infra/.secrets/prod.env from ${existing[*]} ($(grep -c '=' "$PROD_ENV") settings)"

# ---------------------------------------------------------------------------
say "3/5 Waiting for the server's first-boot setup (Docker, swap); about 2-4 minutes on a new server"
for attempt in $(seq 1 60); do
  if remote test -f /var/lib/harmonyhub-ready 2>/dev/null; then
    echo "Server ready."
    break
  fi
  if [ "$attempt" -eq 60 ]; then
    die "Server not ready after 10 minutes. Check: ssh -i infra/.secrets/harmonyhub-ssh.pem ubuntu@$PUBLIC_IP 'sudo tail -50 /var/log/cloud-init-output.log'"
  fi
  sleep 10
done

# ---------------------------------------------------------------------------
say "4/5 Uploading code ($(git describe --tags --always --dirty)) and starting the app; the first build takes 5-10 minutes"
if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
  warn "You have uncommitted changes. Only the last commit is deployed."
fi
git archive --format=tar HEAD | remote \
  'set -e; mkdir -p ~/HarmonyHub; cd ~/HarmonyHub; find . -mindepth 1 -maxdepth 1 ! -name .env -exec rm -rf {} +; tar -x'
upload "$PROD_ENV" "HarmonyHub/.env"
remote "set -e; cd ~/HarmonyHub; chmod 600 .env
  $COMPOSE_CMD up -d --build --wait --remove-orphans
  docker image prune -f >/dev/null"

# ---------------------------------------------------------------------------
say "5/5 Checking https://$PUBLIC_IP (Caddy fetches the HTTPS certificate on first start)"
for attempt in $(seq 1 36); do
  if health="$(curl -fsS --max-time 10 "https://$PUBLIC_IP/api/health" 2>/dev/null)"; then
    echo "$health"
    cat <<DONE

HarmonyHub is live:    https://$PUBLIC_IP
Spotify redirect URI:  https://$PUBLIC_IP/api/auth/spotify/callback   (add it in the Spotify dashboard)
SSH:                   ssh -i infra/.secrets/harmonyhub-ssh.pem ubuntu@$PUBLIC_IP
Redeploy:              ./infra/aws-up.sh
Destroy everything:    ./infra/aws-down.sh
DONE
    exit 0
  fi
  sleep 5
done
warn "The app did not answer over HTTPS within 3 minutes. Recent logs:"
remote "cd ~/HarmonyHub && $COMPOSE_CMD logs --tail 40 caddy backend" || true
exit 1
